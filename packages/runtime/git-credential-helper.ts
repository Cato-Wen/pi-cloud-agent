/**
 * A git credential helper that maps each repository to its own token variable.
 *
 * Git invokes the script with `get` and writes `key=value` lines to stdin. With
 * `credential.useHttpPath` on, those include the host and the repository path,
 * which together select the variable. The script carries variable names only:
 * token values stay in the process environment, never on disk.
 */

export interface CredentialHelperRepo {
  host: string;
  cloneUrl: string;
  tokenVar: string;
}

export function credentialHelperScript(
  repos: CredentialHelperRepo[],
  username: string,
): string {
  const cases = repos
    .map((repo) => `  ${shellPattern(repoKey(repo))}) token="$${repo.tokenVar}" ;;`)
    .join("\n");
  return [
    "#!/bin/sh",
    "# Generated by the runtime: answers git credential requests from the environment.",
    '[ "$1" = "get" ] || exit 0',
    'host=""; path=""',
    "while IFS= read -r line; do",
    '  case "$line" in',
    '    host=*) host="${line#host=}" ;;',
    '    path=*) path="${line#path=}" ;;',
    '    "") break ;;',
    "  esac",
    "done",
    'path="${path#/}"; path="${path%.git}"',
    'case "$host/$path" in',
    cases,
    '  *) token="${SCM_TOKEN:-}" ;;',
    "esac",
    '[ -n "$token" ] || exit 0',
    `printf 'username=%s\\npassword=%s\\n' "\${SCM_TOKEN_USERNAME:-${username}}" "$token"`,
    "",
  ].join("\n");
}

/** "host/owner/name" as git reports it: no scheme, no leading slash, no `.git`. */
function repoKey(repo: CredentialHelperRepo): string {
  let path: string;
  try {
    path = new URL(repo.cloneUrl).pathname;
  } catch {
    path = repo.cloneUrl.replace(/^[a-z]+:\/\/[^/]+/i, "");
  }
  return `${repo.host}/${path.replace(/^\/+/, "").replace(/\.git$/, "")}`;
}

/** Repository names cannot contain shell glob characters, but a stray one must not widen the match. */
function shellPattern(key: string): string {
  return key.replace(/[*?[\]\\|]/g, "\\$&");
}
